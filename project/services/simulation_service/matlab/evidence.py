from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any
from uuid import uuid4

from .config import MatlabIntegrationConfig
from .discovery import discover_matlab


def _now() -> datetime:
    return datetime.now(timezone.utc)


def _stamp(value: datetime) -> str:
    return value.strftime("%Y%m%dT%H%M%SZ")


def write_matlab_demo_evidence(
    *,
    config: MatlabIntegrationConfig,
    demo_name: str,
    engine_type: str,
    is_real_matlab: bool,
    matlab_version: str | None,
    started_at: datetime,
    finished_at: datetime,
    duration_ms: int,
    inputs: dict[str, Any],
    outputs: dict[str, Any],
    formula: str | None,
    assumptions: list[str],
    status: str,
    error: dict[str, Any] | None = None,
) -> dict[str, Any]:
    evidence_id = f"matlab-demo-{uuid4().hex}"
    evidence_dir = config.evidence_dir
    evidence_dir.mkdir(parents=True, exist_ok=True)
    discovery = discover_matlab(config)
    payload = {
        "evidence_id": evidence_id,
        "evidence_type": "matlab_demo_run",
        "phase": "6A",
        "environment": "local",
        "demo_name": demo_name,
        "engine_type": engine_type,
        "is_real_matlab": bool(is_real_matlab),
        "fake_engine_used": engine_type == "fake",
        "real_engine_executed": bool(is_real_matlab),
        "sample_kind": "real" if is_real_matlab else "fake",
        "matlab_root": discovery.matlab_root or config.matlab_root,
        "matlab_version_dir": discovery.selected_version_dir or config.matlab_version_dir,
        "matlab_exe_found": discovery.matlab_exe_found,
        "matlab_exe": discovery.matlab_exe,
        "engine_python_dir": discovery.engine_python_dir,
        "matlab_version": matlab_version or ("fake-engine" if engine_type == "fake" else None),
        "license_confirmed_by_operator": bool(config.operator_confirmed_license),
        "matlab_license_confirmed": bool(config.operator_confirmed_license),
        "human_reviewed": False,
        "human_validated": False,
        "operator": config.operator,
        "started_at": started_at.isoformat(),
        "finished_at": finished_at.isoformat(),
        "duration_ms": int(duration_ms),
        "inputs": dict(inputs),
        "outputs": dict(outputs),
        "formula": formula or "",
        "assumptions": list(assumptions),
        "status": status,
        "error": error,
        "sensitive_fields_redacted": True,
        "validation_notes": "Generated by Phase 6A controlled MATLAB adapter; human validation remains false.",
        "created_at": finished_at.isoformat(),
        "artifacts": [],
    }
    file_base = f"{_stamp(finished_at)}_{demo_name}_{evidence_id}"
    json_path = evidence_dir / f"{file_base}.json"
    md_path = evidence_dir / f"{file_base}.md"
    payload["artifacts"] = [str(json_path), str(md_path)]
    json_path.write_text(json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True), encoding="utf-8")
    lines = [
        "# MATLAB Demo Evidence",
        "",
        f"Evidence id: {evidence_id}",
        f"Phase: {payload['phase']}",
        f"Demo: {demo_name}",
        f"Engine type: {engine_type}",
        f"Real MATLAB: {payload['is_real_matlab']}",
        f"Human validated: {payload['human_validated']}",
        f"Status: {status}",
        "",
        "This artifact is not a license proof and does not mark the result as production validated.",
    ]
    md_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return {"evidence_id": evidence_id, "json_path": json_path, "md_path": md_path, "payload": payload}


__all__ = ["write_matlab_demo_evidence"]
