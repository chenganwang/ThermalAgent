def _card(
    role_id: str,
    name: str,
    description: str,
    stage_name: str | None,
    *,
    inputs: list[str],
    outputs: list[str],
    responsibilities: list[str],
    boundaries: list[str],
    uses_tools: bool = False,
) -> AgentRoleCard:
    return AgentRoleCard(
        role_id=role_id,
        name=name,
        description=description,
        responsibilities=responsibilities,
        inputs=inputs,
        outputs=outputs,
        boundaries=boundaries,
        stage_name=stage_name,
        uses_llm=False,
        uses_tools=uses_tools,
    )


