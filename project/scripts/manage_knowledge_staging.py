"""Inspect, append or withdraw versioned pending-review data; never switch an index."""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from services.ingest_service.knowledge.staging_io import validate_import_package, write_json_exclusive
from services.ingest_service.knowledge.staging_store import StagingStore, TABLES

PROTECTED_TABLES = ('documents', 'chunks', 'knowledge_units', 'source_assets', 'embedding_index')


def connect_mysql():
    import mysql.connector
    from services.retrieval_service.config import load_config
    cfg = load_config(ROOT)
    return mysql.connector.connect(host=cfg.mysql.host, port=cfg.mysql.port,
        user=cfg.mysql.user, password=cfg.mysql.password, database=cfg.mysql.database,
        charset='utf8mb4', connection_timeout=10, autocommit=True)


def mysql_preflight(connection):
    cursor = connection.cursor()
    try:
        cursor.execute('SELECT TABLE_NAME FROM information_schema.tables WHERE TABLE_SCHEMA=DATABASE()')
        existing = {r[0] for r in cursor.fetchall()}
        protected = {}
        for table in PROTECTED_TABLES:
            if table not in existing:
                protected[table] = {'exists': False}
                continue
            cursor.execute(f'SELECT * FROM `{table}` ORDER BY id')
            digest = hashlib.sha256()
            count = 0
            while True:
                records = cursor.fetchmany(100)
                if not records:
                    break
                for row in records:
                    digest.update(json.dumps(row, ensure_ascii=False, separators=(',', ':'), default=str).encode('utf-8'))
                    digest.update(b'\n')
                    count += 1
            protected[table] = {'exists': True, 'count': count, 'sha256': digest.hexdigest()}
        return {'protected_tables': protected, 'staging_tables_present': sorted(set(TABLES) & existing)}
    finally:
        cursor.close()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    target = parser.add_mutually_exclusive_group(required=True)
    target.add_argument('--sqlite', type=Path)
    target.add_argument('--mysql', action='store_true', help='Use configured MySQL; no credentials are printed.')
    parser.add_argument('--init-schema', action='store_true', help='Explicitly create four additive webk_ tables, never ALTER old tables.')
    parser.add_argument('--package', type=Path)
    parser.add_argument('--batch-id')
    parser.add_argument('--withdraw-batch')
    parser.add_argument('--review-json', type=Path, help='Externally completed human review attestation; never autogenerated.')
    parser.add_argument('--record-id', help='Exact immutable unit record ID for --review-json.')
    parser.add_argument('--release-json', type=Path, help='Externally signed publication decision with exact sorted record_ids.')
    parser.add_argument('--commit', action='store_true', help='Execute the append/withdrawal; otherwise validate only.')
    parser.add_argument('--output-dir', type=Path, required=True)
    args = parser.parse_args()
    if sum(bool(x) for x in (args.package,args.withdraw_batch,args.review_json,args.release_json)) != 1:
        parser.error('Choose exactly one package, withdrawal, external review or release action')
    if args.review_json and not args.record_id:
        parser.error('--review-json requires --record-id')
    if args.package and not args.batch_id:
        parser.error('--package requires --batch-id')
    if args.init_schema and not args.commit:
        parser.error('--init-schema requires --commit')
    prepared = validate_import_package(args.package, project_root=ROOT) if args.package else None
    out = args.output_dir.resolve()
    if not out.is_relative_to(ROOT.parent.resolve()):
        parser.error('Output must stay within the project package')
    out.mkdir(parents=True, exist_ok=False)
    if not args.commit:
        report = {'status': 'validated_not_written' if prepared else 'not_executed_not_validated',
                  'validation_scope': 'package artifacts' if prepared else 'target-state and external decision validation require the transactional execution path',
                  'checks': prepared['checks'] if prepared else {},
                  'record_count': len(prepared['records']) if prepared else 0, 'database_written': False}
        write_json_exclusive(out / 'result.json', report)
        print(json.dumps(report, ensure_ascii=False))
        return
    store = None
    preflight = None
    try:
        if args.mysql:
            conn = connect_mysql()
            store = StagingStore(conn, dialect='mysql')
            preflight = mysql_preflight(conn)
            write_json_exclusive(out / 'preflight.json', preflight)
            # All preexisting tables must be present together. Refuse uncertain
            # partial migration state instead of inventing a recovery path.
            present = preflight['staging_tables_present']
            if present and set(present) != set(TABLES):
                raise ValueError('partial_staging_schema_requires_inspection')
            if present:
                write_json_exclusive(out / 'snapshot_before.json', store.snapshot())
            else:
                write_json_exclusive(out / 'snapshot_before.json', {'staging_tables_absent': True})
                if not args.init_schema:
                    raise ValueError('explicit_init_schema_required')
            if args.init_schema:
                store.initialize()
        else:
            location = args.sqlite.resolve()
            if not location.is_relative_to(ROOT.parent.resolve()):
                raise ValueError('sqlite_path_outside_project')
            store = StagingStore.sqlite(location)
            write_json_exclusive(out / 'snapshot_before.json', store.snapshot())
        if prepared:
            report = store.import_batch(args.batch_id, prepared['records'], provenance_manifest=prepared['manifest'])
            report['checks'] = prepared['checks']
        elif args.review_json:
            review = json.loads(args.review_json.read_text(encoding='utf-8-sig'))
            report = store.record_review(args.record_id, review)
        elif args.release_json:
            release = json.loads(args.release_json.read_text(encoding='utf-8-sig'))
            report = store.publish_units(release.get('record_ids', []), release=release)
        else:
            report = store.withdraw_batch(args.withdraw_batch)
        after = store.snapshot()
        write_json_exclusive(out / 'snapshot_after.json', after)
        if args.mysql:
            post = mysql_preflight(store.connection)
            report['protected_tables_unchanged'] = preflight['protected_tables'] == post['protected_tables']
            write_json_exclusive(out / 'postflight.json', post)
            # New data remains recoverable even if unrelated concurrent changes
            # were observed. Do not erase anything or misattribute their cause.
            if not report['protected_tables_unchanged']:
                report['concurrent_change_warning'] = 'Existing table fingerprints changed; investigate before index publication.'
        report.update({'database_operation_executed': True,
                       'database_written': report.get('status') not in {'already_imported','already_recorded'}, 'backend': store.dialect,
                       'published_KU_increment': report.get('updated',0) if args.release_json else 0,
                       'production_index_activated': False,
                       'rollback': {'operation': 'withdraw_batch', 'batch_id': args.batch_id or args.withdraw_batch,
                                    'deletes_original_data': False, 'evidence_rows_retained': True}})
        write_json_exclusive(out / 'result.json', report)
        print(json.dumps(report, ensure_ascii=False))
    except Exception as exc:
        # The exception message may originate in a connection library and expose
        # connection details; keep the public receipt deliberately non-sensitive.
        write_json_exclusive(out / 'failure.json', {'error_type': type(exc).__name__, 'status': 'failed',
            'no_index_activation': True, 'recovery': 'Inspect local preflight/snapshots; transactional import rolls back on failure.'})
        raise SystemExit('staging_failed:' + type(exc).__name__) from None
    finally:
        if store is not None:
            store.close()


if __name__ == '__main__':
    main()
